// ---------------------------------------------------------------- setup

function Setup() {
  const navigate = useNavigate();
  const roles = useAsync(() => api.practiceRoles(), []);
  const history = useAsync(() => api.mockAssessments(), []);
  const [role, setRole] = useState({ job_id: null, role_title: '', skills: [] });
  const [cfg, setCfg] = useState({ difficulty: 'medium', num_mcq: 10, num_coding: 1 });
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState(null);
  const set = (k) => (v) => setCfg((c) => ({ ...c, [k]: v }));
  const coding = roles.data?.code_languages?.length ? cfg.num_coding : 0;
  const minutes = Math.max(5, Math.ceil(cfg.num_mcq * 1.5 + 15 * coding));
  const ready = (role.job_id || role.role_title.trim()) && role.skills.length > 0;
  const start = async () => {
    setBusy(true); setError(null);
    try { const m = await api.createMockAssessment({ ...role, ...cfg, num_coding: coding }); navigate(`/mock-assessment/${m.mock_id}`); }
    catch (e) { setError(e.message); setBusy(false); }
  };
  return (
    <>
      <PageHeader eyebrow="Practice zone" title="Mock assessment"
                  subtitle="A timed practice test built for the role you're preparing for — multiple choice plus real coding problems, graded instantly. Private to you." />
      <div className="practice-layout">
        <section className="card section" style={{ marginTop: 0 }}>
          <h3 className="row" style={{ marginBottom: 12 }}><ClipboardCheck size={18} aria-hidden="true" /> Build your practice test</h3>
          <Async state={roles} loadingLabel="Loading roles…">{(r) => <RolePicker roles={r} value={role} onChange={setRole} />}</Async>
          <div className="setup-grid">
            <Segmented id="ma-diff" label="Difficulty" value={cfg.difficulty} onChange={set('difficulty')}
                       options={[['easy', 'Easy'], ['medium', 'Medium'], ['hard', 'Hard']]} />
            <div className="field">
              <label className="field-label" htmlFor="ma-n">Multiple-choice questions: <b>{cfg.num_mcq}</b></label>
              <input id="ma-n" type="range" min={5} max={20} value={cfg.num_mcq} onChange={(e) => set('num_mcq')(Number(e.target.value))} className="range" />
            </div>
            <Segmented id="ma-code" label="Coding problems" value={String(cfg.num_coding)} onChange={(v) => set('num_coding')(Number(v))}
                       options={[['0', 'None'], ['1', 'One'], ['2', 'Two']]} />
            <div className="field">
              <span className="field-label">Time limit</span>
              <p className="time-preview"><Clock size={15} aria-hidden="true" /> <b>{minutes} minutes</b> <span className="small muted">({cfg.num_mcq} × 1.5 min{coding ? ` + ${coding} × 15 min coding` : ''})</span></p>
            </div>
          </div>
          {!roles.data?.code_languages?.length && roles.data && <p className="small muted">Coding problems are unavailable because no code runtime is configured on the server.</p>}
          {error && <p className="alert alert-danger small" role="alert">{error}</p>}
          <div className="row" style={{ marginTop: 14 }}>
            <span className="small muted">Questions are {roles.data?.ai_available ? 'generated by AI for this role' : 'picked from the skill bank'} · your skill gaps come first.</span>
            <span className="spacer" />
            <button className="btn btn-primary" disabled={!ready || busy} onClick={start}><Play size={15} aria-hidden="true" /> {busy ? 'Building your test…' : 'Start test'}</button>
          </div>
        </section>
        <aside className="practice-side">
          <section className="card section" style={{ marginTop: 0 }}>
            <p className="section-title">Good to know</p>
            <ul className="tick-list">
              <li>The timer runs on the server; your answers save automatically.</li>
              <li>Coding problems run against real tests — try the samples before submitting.</li>
              <li>You get a per-skill breakdown and what to revise next.</li>
              <li>Weak on a topic? Follow up with a <Link to="/mock-interview"><Mic size={12} aria-hidden="true" /> mock interview</Link>.</li>
            </ul>
          </section>
          <section className="card section">
            <p className="section-title">Your mock assessments</p>
            <Async state={history} loadingLabel="Loading…">
              {(rows) => <HistoryList scoreKey="score" empty="No practice tests yet."
                                      onOpen={(r) => navigate(`/mock-assessment/${r.id}`)}
                                      rows={rows.map((r) => ({ ...r, id: r.mock_id, title: r.role_title, sub: `${r.question_count} questions · ${r.config.difficulty} · ${new Date(r.started_at).toLocaleDateString()}` }))} />}
            </Async>
          </section>
        </aside>
      </div>
    </>
  );
}

// ---------------------------------------------------------------- test

function CodingQ({ q, value, onChange, mockId, locked }) {
  const p = q.problem;
  const langs = p?.languages || [];
  const language = value?.language && langs.some((l) => l.key === value.language) ? value.language : (langs[0]?.key || 'python');
  const starter = (key) => langs.find((l) => l.key === key)?.starter || '';
  const source = value?.source ?? starter(language);
  const [result, setResult] = useState(null);
  const [busy, setBusy] = useState(false);
  if (!p) return <p className="alert alert-warn">This coding problem is unavailable.</p>;
  if (!langs.length) return <p className="alert alert-warn">No programming language runtime is available on the server right now.</p>;
  const run = async () => {
    if (busy || locked) return;
    if (!source.trim()) { setResult({ error: 'Write some code first.', tests: [] }); return; }
    setBusy(true);
    try { setResult(await api.mockAssessmentRunCode(mockId, { question_index: q.index, language, source })); }
    catch (e) { setResult({ error: e.message, tests: [] }); } finally { setBusy(false); }
  };
  const changeLanguage = (key) => {
    if (key === language) return;
    if (source.trim() && source !== starter(language) && !window.confirm('Switch language? Your current code will be replaced by the starter template.')) return;
    onChange({ language: key, source: starter(key) });
    setResult(null);
  };
  const reset = () => {
    if (source !== starter(language) && !window.confirm('Reset to the starter template? Your current code will be lost.')) return;
    onChange({ language, source: starter(language) });
    setResult(null);
  };
  return (
    <div className="coding-split">
      <div className="problem-pane">
        <p style={{ whiteSpace: 'pre-wrap' }}>{p.statement}</p>
        {p.input_format && <><p className="section-title" style={{ margin: '12px 0 4px' }}>Input</p><p className="small" style={{ whiteSpace: 'pre-wrap' }}>{p.input_format}</p></>}
        {p.output_format && <><p className="section-title" style={{ margin: '12px 0 4px' }}>Output</p><p className="small" style={{ whiteSpace: 'pre-wrap' }}>{p.output_format}</p></>}
        {p.constraints && <pre className="pre small">{p.constraints}</pre>}
        {(p.examples || []).map((ex, i) => <pre key={i} className="pre small">{`Example ${i + 1}\nInput:\n${ex.input}\nOutput:\n${ex.output}`}</pre>)}
        <p className="small muted" style={{ marginTop: 10 }}>Read from standard input, print to standard output. Hidden tests run when you submit the test.</p>
      </div>
      <div style={{ minWidth: 0 }}>
        <div className="code-toolbar">
          <label className="sr-only" htmlFor={`ma-lang-${q.index}`}>Language</label>
          <select id={`ma-lang-${q.index}`} className="input input-sm" style={{ width: 150 }} value={language} disabled={locked || busy}
                  onChange={(e) => changeLanguage(e.target.value)}>
            {langs.map((l) => <option key={l.key} value={l.key}>{l.label}</option>)}
          </select>
          <button type="button" className="icon-btn" onClick={reset} disabled={locked || busy} title="Reset to starter template" aria-label="Reset to starter template"><RotateCcw size={15} aria-hidden="true" /></button>
          <span className="spacer" />
          <button className="btn btn-secondary btn-sm" disabled={busy || locked} onClick={run}><Play size={14} aria-hidden="true" /> {busy ? 'Running…' : 'Run samples'}</button>
        </div>
        <CodeEditor value={source} onChange={(s) => onChange({ language, source: s })} language={language} label={`Code for ${q.question}`} readOnly={locked} onRun={run} minHeight={300} />
        <CodeRunResult result={result} title="Sample run" />
      </div>
    </div>
  );
}

function TestRunner({ m, setM }) {
  const { toast } = useApp();
  const [answers, setAnswers] = useState(m.answers || {});
  const [code, setCode] = useState(m.code || {});
  const [flags, setFlags] = useState({});
  const [i, setI] = useState(0);
  const [confirm, setConfirm] = useState(false);
  const [busy, setBusy] = useState(false);
  const dirty = useRef(false);
  const deadline = useMemo(() => Date.now() + m.remaining_s * 1000, [m.mock_id]); // eslint-disable-line react-hooks/exhaustive-deps
  const q = m.questions[i];

  const submit = useCallback(async (auto = false) => {
    setConfirm(false); setBusy(true);
    try { setM(await api.submitMockAssessment(m.mock_id, { answers, code })); if (auto) toast('Time is up — your test was submitted', 'info'); }
    catch (e) { toast(e.message, 'danger'); setBusy(false); }
  }, [m.mock_id, answers, code, setM, toast]);
  const left = useCountdown(deadline, () => submit(true));

  // Autosave every 5 s when something changed.
  useEffect(() => {
    const id = setInterval(() => {
      if (!dirty.current) return;
      dirty.current = false;
      api.saveMockAssessment(m.mock_id, { answers, code }).catch(() => { dirty.current = true; });
    }, 5000);
    return () => clearInterval(id);
  }, [m.mock_id, answers, code]);
  const answer = (v) => { dirty.current = true; setAnswers((a) => ({ ...a, [q.index]: v })); };
  const setQCode = (v) => { dirty.current = true; setCode((c) => ({ ...c, [q.index]: v })); };
  const isDone = (x) => {
    if (x.type === 'mcq') return !!answers[x.index];
    const c = code[x.index];
    const starter = (x.problem?.languages || []).find((l) => l.key === c?.language)?.starter || '';
    return !!(c?.source || '').trim() && c.source.trim() !== starter.trim();
  };
  const doneCount = m.questions.filter(isDone).length;

  return (
    <div className="test-layout">
      <aside className="test-nav card">
        <div className="row" style={{ justifyContent: 'center' }}><TimerRing left={left ?? m.remaining_s} total={m.time_limit_minutes * 60} size={84} /></div>
        <p className="small muted" style={{ textAlign: 'center', margin: '6px 0 12px' }}>{doneCount}/{m.questions.length} answered · saved automatically</p>
        <div className="q-grid" role="list" aria-label="Questions">
          {m.questions.map((x, k) => (
            <button key={x.index} type="button" role="listitem" aria-current={k === i} aria-label={`Question ${k + 1}${isDone(x) ? ', answered' : ''}${flags[x.index] ? ', flagged' : ''}`}
                    className={`q-dot${k === i ? ' cur' : ''}${isDone(x) ? ' done' : ''}${flags[x.index] ? ' flag' : ''}`} onClick={() => setI(k)}>
              {x.type === 'coding' ? '</>' : k + 1}
            </button>
          ))}
        </div>
        <div className="q-legend small muted"><span><i className="q-dot done" /> answered</span><span><i className="q-dot flag" /> flagged</span></div>
        <button className="btn btn-primary btn-block" style={{ marginTop: 12 }} disabled={busy} onClick={() => setConfirm(true)}><Send size={14} aria-hidden="true" /> {busy ? 'Grading…' : 'Submit test'}</button>
      </aside>

      <section className="card section" style={{ marginTop: 0, minWidth: 0 }}>
        <div className="row" style={{ marginBottom: 10 }}>
          <span className="pill pill-brand">Question {i + 1} of {m.questions.length}</span>
          <span className="pill pill-neutral">{q.skill}</span>
          <span className="small muted">{q.difficulty}</span>
          <span className="spacer" />
          <button type="button" className={`btn btn-sm ${flags[q.index] ? 'btn-primary' : 'btn-secondary'}`} onClick={() => setFlags((f) => ({ ...f, [q.index]: !f[q.index] }))}>
            <Flag size={13} aria-hidden="true" /> {flags[q.index] ? 'Flagged' : 'Flag for review'}
          </button>
        </div>
        <h2 className="question-text">{q.question}</h2>
        {q.type === 'mcq' ? (
          <div className="option-list" role="radiogroup" aria-label="Options">
            {q.options.map((o) => (
              <button key={o.label} type="button" role="radio" aria-checked={answers[q.index] === o.label}
                      className={`option${answers[q.index] === o.label ? ' on' : ''}`} onClick={() => answer(o.label)}>
                <span className="option-key">{o.label}</span><span>{o.text}</span>
              </button>
            ))}
          </div>
        ) : <CodingQ key={q.index} q={q} value={code[q.index]} onChange={setQCode} mockId={m.mock_id} locked={busy} />}
        <div className="row" style={{ marginTop: 16 }}>
          <button className="btn btn-secondary btn-sm" disabled={i === 0} onClick={() => setI(i - 1)}><ChevronLeft size={14} aria-hidden="true" /> Previous</button>
          {q.type === 'mcq' && answers[q.index] && <button className="btn btn-secondary btn-sm" onClick={() => answer('')}>Clear answer</button>}
          <span className="spacer" />
          {i < m.questions.length - 1
            ? <button className="btn btn-primary btn-sm" onClick={() => setI(i + 1)}>Next <ChevronRight size={14} aria-hidden="true" /></button>
            : <button className="btn btn-primary btn-sm" onClick={() => setConfirm(true)}>Finish <Send size={13} aria-hidden="true" /></button>}
        </div>
      </section>

      {confirm && (
        <Modal title="Submit your practice test?" onClose={() => setConfirm(false)}
               footer={<><button className="btn btn-secondary" onClick={() => setConfirm(false)}>Keep working</button><button className="btn btn-primary" onClick={() => submit(false)}>Submit</button></>}>
          <p>You answered <b>{doneCount}</b> of {m.questions.length} questions{Object.values(flags).some(Boolean) ? ` and flagged ${Object.values(flags).filter(Boolean).length}` : ''}. {fmtClock(Math.max(0, left ?? 0))} left.</p>
        </Modal>
      )}
    </div>
  );
}

// ---------------------------------------------------------------- results

function Results({ m }) {
  const navigate = useNavigate();
  const r = m.results;
  const byIndex = Object.fromEntries(r.questions.map((x) => [x.index, x]));
  const [filter, setFilter] = useState('all');
  const qs = m.questions.filter((q) => filter === 'all' || (filter === 'wrong' ? (byIndex[q.index]?.points ?? 0) < 1 : (byIndex[q.index]?.points ?? 0) >= 1));
  return (
    <div className="practice-layout">
      <div style={{ minWidth: 0, display: 'grid', gap: 14 }}>
        <section className="card section report-hero" style={{ marginTop: 0 }}>
          <ScoreRing value={m.score} label="score" />
          <div style={{ flex: 1, minWidth: 220 }}>
            <p className="eyebrow">{m.role_title} · {m.config.difficulty}</p>
            <h2 style={{ margin: '4px 0 6px' }}>Practice test results</h2>
            <p className="small">{m.auto_submitted ? 'Submitted automatically when time ran out. ' : ''}{r.correct} of {r.total} questions fully correct.</p>
            <div className="mini-stats" style={{ marginTop: 12 }}>
              <div><b>{r.correct}/{r.total}</b><span>correct</span></div>
              <div><b>{Math.round((new Date(m.completed_at) - new Date(m.started_at)) / 60000)}m</b><span>time taken</span></div>
              <div><b>{m.time_limit_minutes}m</b><span>limit</span></div>
              <div><b>{m.engine === 'ai' ? 'AI' : 'Bank'}</b><span>questions</span></div>
            </div>
          </div>
        </section>
        <section className="card section" style={{ marginTop: 0 }}>
          <div className="row" style={{ marginBottom: 10 }}>
            <p className="section-title" style={{ margin: 0 }}>Review answers</p><span className="spacer" />
            <div className="seg seg-sm" role="radiogroup" aria-label="Filter">
              {[['all', 'All'], ['wrong', 'Incorrect'], ['right', 'Correct']].map(([k, l]) => <button key={k} type="button" role="radio" aria-checked={filter === k} className={filter === k ? 'on' : ''} onClick={() => setFilter(k)}>{l}</button>)}
            </div>
          </div>
          <div className="review-list">
            {qs.map((q) => {
              const res = byIndex[q.index] || {};
              const ok = (res.points ?? 0) >= 1;
              return (
                <details key={q.index} className="review-item" open={!ok && filter === 'wrong'}>
                  <summary>
                    {ok ? <CircleCheck size={18} className="tone-ok" aria-label="correct" /> : <CircleX size={18} className="tone-danger" aria-label="incorrect" />}
                    <span className="review-q"><b>Q{q.index + 1}</b> {q.question}</span>
                    <span className="pill pill-neutral">{q.skill}</span>
                  </summary>
                  <div className="review-body">
                    {q.type === 'mcq' ? (
                      <ul className="option-review">
                        {q.options.map((o) => (
                          <li key={o.label} className={o.label === q.correct ? 'correct' : o.label === res.given ? 'given' : ''}>
                            <b>{o.label}.</b> {o.text}{o.label === q.correct ? ' — correct answer' : o.label === res.given ? ' — your answer' : ''}
                          </li>
                        ))}
                      </ul>
                    ) : <p className="small">{res.passed ?? 0}/{res.total ?? 0} tests passed ({String(res.status || 'not submitted').replace('_', ' ')}){res.error ? ' — the code did not compile or crashed.' : ''}</p>}
                    {q.explanation && <p className="small muted" style={{ marginTop: 6 }}>Why: {q.explanation}</p>}
                  </div>
                </details>
              );
            })}
          </div>
        </section>
      </div>
      <aside className="practice-side">
        <section className="card section" style={{ marginTop: 0 }}>
          <p className="section-title">By skill</p>
          <ScoreBars items={r.skills} valueKey="percent" labelKey="skill" />
        </section>
        <section className="card section">
          <p className="section-title">What to do next</p>
          <ul className="tick-list warn">{r.recommendations.map((x) => <li key={x}>{x}</li>)}</ul>
          <div style={{ display: 'grid', gap: 8, marginTop: 12 }}>
            <button className="btn btn-primary btn-block" onClick={() => navigate('/mock-assessment')}><RotateCcw size={14} aria-hidden="true" /> New practice test</button>
            <Link className="btn btn-secondary btn-block" to="/mock-interview"><Mic size={14} aria-hidden="true" /> Mock interview</Link>
          </div>
        </section>
      </aside>
    </div>
  );
}

function Session({ id }) {
  const [m, setM] = useState(null);
  const [error, setError] = useState(null);
  useEffect(() => { api.mockAssessment(id).then(setM).catch(setError); }, [id]);
  if (error) return <ErrorState error={error} label="Couldn't load this practice test" />;
  if (!m) return <LoadingState label="Loading test…" />;
  const done = m.status === 'completed';
  return (
    <>
      <PageHeader eyebrow={`Practice zone · ${m.role_title} · private to you`} title={done ? 'Mock assessment results' : 'Mock assessment'}
                  actions={<Link className="btn btn-secondary btn-sm" to="/mock-assessment">All practice tests</Link>} />
      {done ? <Results m={m} /> : <TestRunner m={m} setM={setM} />}
    </>
  );
}

export default function MockAssessment() {
  const { id } = useParams();
  return id ? <Session key={id} id={id} /> : <Setup />;
}
